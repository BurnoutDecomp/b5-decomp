def wiring(tree):
    bat = BUILD_BAT.read_text(encoding="utf-8", errors="replace") if BUILD_BAT.exists() else ""
    yield ("the exe mounts MomentController\\Moments\\BrnMomentPlayerJumping.cpp (tools/build/build_game_exe.bat)",
           'echo "%SRC%\\GameSource\\Director\\MomentController\\Moments\\BrnMomentPlayerJumping.cpp"' in bat)
    try:
        new_moment = re.sub(r"\s+", "", code_only(definition(tree.read(CONTROLLER_CPP),
                                                             "bool MomentController::NewMoment(")))
    except ValueError:
        new_moment = ""
    yield ("MomentController::NewMoment allocates type 7 (jpt_822558C4 case 7: AllocateVoid<MomentPlayerJumping> "
           "@0x82252DB8), ungated", "caseMoment::E_MOMENT_PLAYER_JUMPING:lVoidHandle=mMomentPool.AllocateVoid<"
           "MomentPlayerJumping>();break;" in new_moment)


def numeric(tree, output_dir=None):
    jumping = tree.read(JUMPING_CPP)
    texts = {relative: tree.read(relative) for relative in SOURCES}
    if not jumping or not all(texts.values()):
        print("NUMERIC: the revision lacks the jump moment's TU or its leaves")
        return None

    shadow = {relative: tree.read(relative) for relative in HEADERS}
    shadow.update(TEST_SHADOWS)

    inc_text = "// GENERATED by run_fxdirector2_player_jumping.py\n" + jumping
    test_cpp = Path(__file__).with_name("FxDirector2PlayerJumping.cpp")
    if output_dir is None:
        with tempfile.TemporaryDirectory(prefix="brn_fxd2_pjump_") as directory:
            extra = []
            for relative, source_text in texts.items():
                target = Path(directory) / Path(relative).name
                target.write_text(source_text, encoding="utf-8")
                extra.append(target)
            return compile_and_run(test_cpp, "fxd2_player_jumping.inc", inc_text,
                                   "FxDirector2PlayerJumping", shadow=shadow,
                                   extra_sources=tuple(extra))

    destination = Path(output_dir).resolve()
    source_dir = destination.with_name(destination.name + "_sources")
    if source_dir.exists() and any(source_dir.iterdir()):
        raise ValueError("Refusing to overwrite retained fixture inputs: " + str(source_dir))
    source_dir.mkdir(parents=True, exist_ok=True)
    extra = []
    for relative, source_text in texts.items():
        target = source_dir / Path(relative).name
        target.write_text(source_text, encoding="utf-8")
        extra.append(target)
    return compile_and_run(test_cpp, "fxd2_player_jumping.inc", inc_text,
                           "FxDirector2PlayerJumping", shadow=shadow,
                           extra_sources=tuple(extra), output_dir=destination)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--rev", help="read the b5 sources from this git revision")
    parser.add_argument("--output-dir", help="retain generated source, command, binary and receipts here")
    parser.add_argument("--workflow-root", help="use this workflow checkout's canonical build flags/includes")
    args = parser.parse_args()
    if args.workflow_root:
        global WORKFLOW, BUILD_BAT
        WORKFLOW = Path(args.workflow_root).resolve()
        fxgs_common.WORKFLOW = WORKFLOW
        BUILD_BAT = WORKFLOW / "tools/build/build_game_exe.bat"
    tree = Tree(args.rev)
    return report("run_fxdirector2_player_jumping", list(wiring(tree)),
                  numeric(tree, args.output_dir), NUMERIC_CHECKS)


if __name__ == "__main__":
    sys.exit(main())

