struct TestAllocator : rw::IResourceAllocator
{
    struct Request { u32 muSize; u32 muAlignment; };
    std::vector<void*>   maBlocks;
    std::vector<Request> maRequests;
    ::rw::Resource DoAllocate(const ::rw::ResourceDescriptor& lrDescriptor, const char*) override
    {
        const u32 luSize  = lrDescriptor.m_baseResourceDescriptors[0].m_size;
        const u32 luAlign = lrDescriptor.m_baseResourceDescriptors[0].m_alignment;
        maRequests.push_back(Request{ luSize, luAlign });
        void* lpBlock = _aligned_malloc(luSize ? luSize : 16u, luAlign < 16u ? 16u : luAlign);
        std::memset(lpBlock, 0, luSize ? luSize : 16u);
        maBlocks.push_back(lpBlock);
        ::rw::Resource lResource;
        lResource.m_baseResources[0] = lpBlock;
        return lResource;
    }
    ~TestAllocator() { for (void* lpBlock : maBlocks) { _aligned_free(lpBlock); } }
};

