static void Check(bool lbPass, const std::string& lrWhat)
{
    ++gChecks;
    if (!lbPass)
    {
        ++gFailures;
        std::printf("FAIL: %s\n", lrWhat.c_str());
    }
}

int main()
{
    // ---- GetFrustumPerspectiveVertices: the 32 words of the 8 corners, bitwise ----
    const size_t luNumFrustum = sizeof(kFrustumCases) / sizeof(kFrustumCases[0]);
    for (size_t luCase = 0; luCase < luNumFrustum; ++luCase)
    {
        const FrustumCase& lrCase = kFrustumCases[luCase];
        CgsGraphics::Camera lCamera;
        std::memset(&lCamera, 0, sizeof(lCamera));
        LoadCamera(lCamera, lrCase.mauView, lrCase.muTanH, lrCase.muTanV, lrCase.muNear, lrCase.muFar);
        Vector3 laVerts[8];
        std::memset(laVerts, 0xCD, sizeof(laVerts));
        lCamera.GetFrustumPerspectiveVertices(laVerts);
        u32 luFirstBad = 32;
        for (u32 i = 0; i < 32 && luFirstBad == 32; ++i)
        {
            const Vector3& lrV = laVerts[i / 4];
            const f32 lfLane = (i % 4 == 0) ? lrV.x : (i % 4 == 1) ? lrV.y : (i % 4 == 2) ? lrV.z : lrV.w;
            if (Bits(lfLane) != lrCase.mauVerts[i])
            {
                luFirstBad = i;
            }
        }
        char lacDetail[240];
        if (luFirstBad < 32)
        {
            const Vector3& lrV = laVerts[luFirstBad / 4];
            const f32 lfLane = (luFirstBad % 4 == 0) ? lrV.x : (luFirstBad % 4 == 1) ? lrV.y : (luFirstBad % 4 == 2) ? lrV.z : lrV.w;
            std::snprintf(lacDetail, sizeof(lacDetail), " (first difference: corner %u lane %u, PC %08X console %08X)",
                          luFirstBad / 4, luFirstBad % 4, Bits(lfLane), lrCase.mauVerts[luFirstBad]);
        }
        else
        {
            lacDetail[0] = 0;
        }
        Check(luFirstBad == 32, std::string("[frustum: ") + lrCase.mpcName
                                    + "] the 8 corners, all 32 words, as the console's 0x827E70E0" + lacDetail);
    }

    // ---- RenderTrafficLightCoronas: the renderers' calls, phase by phase ----
    const u32 luNumCells = kGridX * kGridZ;
    static Pvs sPvs;
    std::memset(&sPvs, 0, sizeof(sPvs));
    sPvs.mGridMin       = Lane(kGridMin);
    sPvs.mRecipCellSize = Lane(kGridRecip);
    sPvs.muNumCells_X   = kGridX;
    sPvs.muNumCells_Z   = kGridZ;
    sPvs.muNumCells     = luNumCells;
    static Hull saHulls[kGridX * kGridZ];
    static Hull* sapHulls[kGridX * kGridZ];
    for (u32 k = 0; k < luNumCells; ++k)
    {
        saHulls[k].muIndex = k;
        sapHulls[k]        = &saHulls[k];
    }
    static TrafficData sData;
    sData.muNumHulls = static_cast<u16>(luNumCells);
    sData.mpPvs      = &sPvs;
    sData.mpapHulls  = sapHulls;

    static int siInterfaceTag;
    BrnCoronaManager::BrnSubmissionInterface* const lpInterface =
        reinterpret_cast<BrnCoronaManager::BrnSubmissionInterface*>(&siInterfaceTag);

    const size_t luNumPass = sizeof(kPassCases) / sizeof(kPassCases[0]);
    unsigned luConsolePhase2 = 0;
    for (size_t luCase = 0; luCase < luNumPass; ++luCase)
    {
        const PassCase& lrCase = kPassCases[luCase];
        const std::string lName = std::string("[pass: ") + lrCase.mpcName + "] ";

        static TrafficEntityModule sModule;
        std::memset(&sModule, 0, sizeof(sModule));
        sModule.mpData.mpResource = &sData;
        sModule.mActiveHullsForLocalPlayer.Construct();
        for (u32 a = 0; a < lrCase.muNumActive; ++a)
        {
            sModule.mActiveHullsForLocalPlayer.Insert(static_cast<u16>(kPassActive[lrCase.muActiveStart + a]));
        }
        gpuCaseView       = lrCase.mauView;
        gauCaseScalars[0] = lrCase.muTanH;
        gauCaseScalars[1] = lrCase.muTanV;
        gauCaseScalars[2] = lrCase.muNear;
        gauCaseScalars[3] = lrCase.muFar;

        gPassCalls.clear();
        gFarPlanes.clear();
        gAsserts.clear();
        guCopies = 0;
        sModule.RenderTrafficLightCoronas(lpInterface, Lane(lrCase.mauV1), Lane(lrCase.mauV2));

        std::vector<const PassCall*> laPhase1, laPhase2;
        bool lbOrder = true;   // every phase-1 call precedes every phase-2 call, as on the console
        for (const PassCall& lrCall : gPassCalls)
        {
            if (lrCall.muPhase == 1)
            {
                lbOrder = lbOrder && laPhase2.empty();
                laPhase1.push_back(&lrCall);
            }
            else
            {
                laPhase2.push_back(&lrCall);
            }
        }

        bool lbPhase1 = lbOrder && (laPhase1.size() == lrCase.muNumPhase1);
        for (size_t i = 0; lbPhase1 && i < laPhase1.size(); ++i)
        {
            const u32* lpuExpected = &kPassPhase1[13 * (lrCase.muPhase1Start + i)];
            lbPhase1 = laPhase1[i]->muHull == lpuExpected[0] && laPhase1[i]->mpManager == &sModule.mTrafficLightManager
                       && laPhase1[i]->mpCollection == &sData.mTrafficLights && laPhase1[i]->mpInterface == lpInterface
                       && std::memcmp(laPhase1[i]->mauV, lpuExpected + 1, sizeof(laPhase1[i]->mauV)) == 0;
        }
        char lacDetail[200];
        std::snprintf(lacDetail, sizeof(lacDetail),
                      "the active hulls -> RenderLightsForHull, call by call (hull, v1/v2/v3 bitwise): %u, console %u",
                      static_cast<unsigned>(laPhase1.size()), lrCase.muNumPhase1);
        Check(lbPhase1, lName + lacDetail);

        bool lbPhase2 = (laPhase2.size() == lrCase.muNumPhase2);
        for (size_t i = 0; lbPhase2 && i < laPhase2.size(); ++i)
        {
            const u32* lpuExpected = &kPassPhase2[14 * (lrCase.muPhase2Start + i)];
            lbPhase2 = laPhase2[i]->muHull == lpuExpected[0] && laPhase2[i]->muMask == lpuExpected[1]
                       && laPhase2[i]->mpManager == &sModule.mTrafficLightManager
                       && laPhase2[i]->mpCollection == &sData.mTrafficLights && laPhase2[i]->mpInterface == lpInterface
                       && std::memcmp(laPhase2[i]->mauV, lpuExpected + 2, sizeof(laPhase2[i]->mauV)) == 0;
        }
        std::snprintf(lacDetail, sizeof(lacDetail),
                      "the frustum's other hulls -> RenderAllLightsToBeInStateForHull, call by call (hull, mask, "
                      "v1/v2/v3 bitwise): %u, console %u",
                      static_cast<unsigned>(laPhase2.size()), lrCase.muNumPhase2);
        Check(lbPhase2, lName + lacDetail);
        luConsolePhase2 += lrCase.muNumPhase2;

        Check(guCopies == 1 && gFarPlanes.size() == 1 && gFarPlanes[0] == 0x43FA0000u,
              lName + "the frustum camera: mCameraLastFrame copied once, its far plane set to 500 (flt_8200A034) once");

        Check(gAsserts.empty() && lrCase.muAsserts == 0, lName + "no tripwire fires, as on the console");
    }

    Check(luConsolePhase2 > 300, "the data exercises the frustum walk (more than 300 console phase-2 calls)");

    std::printf("FxTrafficLightCoronasPass: %u checks, %u failures\n", gChecks, gFailures);
    return gFailures == 0 ? 0 : 1;
}
