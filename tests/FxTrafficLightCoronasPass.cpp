static f32 Val(u32 luBits)
{
    f32 lfValue;
    std::memcpy(&lfValue, &luBits, sizeof(lfValue));
    return lfValue;
}

static u32 Bits(f32 lfValue)
{
    u32 luBits;
    std::memcpy(&luBits, &lfValue, sizeof(luBits));
    return luBits;
}

static Vector3 Lane(const u32* lpuBits)
{
    const Vector3 lLane = { Val(lpuBits[0]), Val(lpuBits[1]), Val(lpuBits[2]), Val(lpuBits[3]) };
    return lLane;
}

static Vector4 Lane4(const u32* lpuBits)
{
    const Vector4 lLane = { Val(lpuBits[0]), Val(lpuBits[1]), Val(lpuBits[2]), Val(lpuBits[3]) };
    return lLane;
}

static void LoadCamera(CgsGraphics::Camera& lrCamera, const u32* lpuView, u32 luTanH, u32 luTanV, u32 luNear, u32 luFar)
{
    lrCamera.mView.xAxis = Lane4(&lpuView[0]);
    lrCamera.mView.yAxis = Lane4(&lpuView[4]);
    lrCamera.mView.zAxis = Lane4(&lpuView[8]);
    lrCamera.mView.wAxis = Lane4(&lpuView[12]);
    lrCamera.maProjectionScalars[2] = Val(luTanH);   // +0x148 m_tanHalfFovHorizontal
    lrCamera.maProjectionScalars[5] = Val(luTanV);   // +0x154 m_tanHalfFovVertical
    lrCamera.maProjectionScalars[7] = Val(luNear);   // +0x15C m_nearClipPlane
    lrCamera.maProjectionScalars[8] = Val(luFar);    // +0x160 m_farClipPlane
}

