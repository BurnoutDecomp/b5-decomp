// GetCurveOutput @0x82B45160 -- evaluate eMIXTABLEID curve `liId` at position liPos
// [0,0x7FFF]; if lbDb, return the result as dB (hundredths) instead of a Q15 amplitude.
// The 5 "UP" shapes (odd ids) remap to their "DWN" pair (id-1): amplitude form inverts
// the position; dB form negates the DWN dB. SQ shapes square the amplitude (or 2x the dB).
// ONE_MIN uses 0x7FFF - eqpwr; LINEAR is 0x7FFF - pos.
// ---------------------------------------------------------------------------
int GetCurveOutput(int liId, int liPos, char lbDb)
{
    switch (liId)
    {
    case 1: case 3: case 5: case 7: case 9:   // UP_* -> DWN_* (id-1)
        if (lbDb)
            return -GetCurveOutput(liId - 1, liPos, 1);          // loc_82B453A0
        return GetCurveOutput(liId - 1, 0x7FFF - liPos, 0);      // invert position, re-dispatch

    case 0:   // DWN_EQPWR  (loc_82B4522C)
    {
        const int liIdx = liPos >> 6;
        int liR = kEqPower[liIdx];
        if (liR != 0)
            liR += (((kEqPower[liIdx + 1] - liR) * CurveFrac(liPos)) >> 15);
        if (lbDb)
        {
            liR = GetdBFromQ15(liR);
            if (liR < -0x2580) liR = -0x2710;
        }
        return liR;
    }

    case 2:   // DWN_EQPWR_SQ  (loc_82B4529C)
        if (lbDb)
        {
            int liR = GetCurveOutput(0, liPos, 1) << 1;          // 2x dB == squared amplitude
            if (liR < -0x2580) liR = -0x2710;
            return liR;
        }
        else
        {
            const int liR = GetCurveOutput(0, liPos, 0);
            return static_cast<int>((static_cast<long long>(liR) * liR) >> 15);
        }

    case 4:   // DWN_ONE_MIN_EQPWR  (loc_82B452F4)
    {
        const int liIdx = 0x1FF - (liPos >> 6);
        const int liFrac = CurveFrac(liPos);
        const int liV  = 0x7FFF - kEqPower[liIdx];
        const int liV2 = 0x7FFF - kEqPower[liIdx + 1];
        int liR = liV + (((liV2 - liV) * liFrac) >> 15);
        if (lbDb)
        {
            liR = GetdBFromQ15(liR);
            if (liR < -0x2580) liR = -0x2710;
        }
        return liR;
    }

    case 6:   // DWN_ONE_MIN_EQPWR_SQ  (loc_82B45368)
        if (lbDb)
        {
            int liR = GetCurveOutput(4, liPos, 1) << 1;
            if (liR < -0x2580) liR = -0x2710;
            return liR;
        }
        else
        {
            const int liR = GetCurveOutput(4, liPos, 0);
            return static_cast<int>((static_cast<long long>(liR) * liR) >> 15);
        }

    case 8:   // DWN_LINEAR  (loc_82B45208)
    {
        int liR = 0x7FFF - liPos;
        if (lbDb)
            liR = GetdBFromQ15(liR);
        return liR;
    }

    default:
        return 0;
    }
}

