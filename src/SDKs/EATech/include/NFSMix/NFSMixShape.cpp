// ---------------------------------------------------------------------------
// GetdBFromQ15 @0x82B45060 -- amplitude (Q15) -> dB in hundredths (<=0). The leading
// set bit picks the octave (602 hundredths-dB = 6.02 dB each); a 9-bit mantissa indexes
// the within-octave log table. VERIFIED == round(602*log2(q15/32768)) across the range.
// ---------------------------------------------------------------------------
int GetdBFromQ15(int liQ15)
{
    if (liQ15 == 0)
        return 0;
    static const int kMantissaMask[12] = { 0, 1, 3, 7, 0xF, 0x1F, 0x3F, 0x7F, 0xFF, 0x1FF, 0x3FF, 0x7FF };
    int liBit = 0;                                   // leading-bit search from 0x4000
    if (!(liQ15 & 0x4000))
    {
        do {
            if (liBit == 0x10)
                return 0;
            ++liBit;
        } while (!((0x4000 >> liBit) & liQ15));
    }
    const int liRem = liQ15 - (0x4000 >> liBit);     // remove the leading bit
    const int liSeg = (-1 - liBit) * 602;            // octave offset (hundredths-dB)
    int liIdx;
    if (liBit >= 5)
        liIdx = (liRem << (liBit - 5)) | kMantissaMask[liBit - 5];
    else
        liIdx = liRem >> (5 - liBit);
    return kQ15ToDb[liIdx] + liSeg;
}

// ---------------------------------------------------------------------------
// GetQ15FromHundredthsdB @0x82B44ED0 -- dB (hundredths) -> Q15 gain. >=0 dB clamps to
// full scale; else the octave count liQ comes from the 0xE4C8B7B5 signed-mulhi magic,
// the antilog table is read at [601 + liQ*602 + hdB] (601 == word_82F8677A) and shifted
// down liQ octaves, then floored to 0 below ~50.
// ---------------------------------------------------------------------------
int GetQ15FromHundredthsdB(int liHundredthsDb)
{
    if (liHundredthsDb >= 0)
        return 0x7FFF;
    int liQ = static_cast<int>((static_cast<long long>(liHundredthsDb) * static_cast<int>(0xE4C8B7B5)) >> 32);
    liQ >>= 6;
    liQ += static_cast<int>(static_cast<unsigned int>(liQ) >> 31);   // + sign bit
    int liIdx = 601 + liQ * 602 + liHundredthsDb;    // base word_82F8677A == kDbToQ15[601]
    // FLAG (PC safety): the X360 trusts the input range and reads adjacent rodata for an
    // out-of-range index; clamp here so the PC can't read past the table (the >>liQ + the
    // >50 floor below already drive extreme inputs to 0).
    if (liIdx < 0) liIdx = 0;
    else if (liIdx > 601) liIdx = 601;
    const int liR = kDbToQ15[liIdx] >> liQ;
    return (liR > 50) ? liR : 0;
}

