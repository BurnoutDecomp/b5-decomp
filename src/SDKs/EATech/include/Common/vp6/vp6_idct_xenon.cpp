//
// The three variants dequantise in float (coefficient times its float factor, truncated back to an
// integer), then run the transform with every cosine product done as a float multiply truncated to
// an integer and shifted down by 16, with saturating adds. The statement sequence follows the vector
// unit's dataflow register for register; the lane-exact vector model is in vp6_xenon_vmx.h, the
// constant registers are VP6_XenonConstants.

