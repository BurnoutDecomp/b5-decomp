// DC-only block: every residual sample is (dequantised DC + 15) >> 5.
// Clears the DC coefficient.
void IDct1_Xenon(short* Coeffs, const short* Dequant, short* ReconData)
{
    VmxVector v0, v11, v12, v13;

    v12 = VmxLoadS16(Coeffs + 0);
    v12 = VmxUnpackHighSH(v12);
    v13 = VmxLoadImage(VP6_XenonConstants[12]);
    v0 = VmxLoadImage(VP6_XenonConstants[9]);
    v11 = VmxConvertFromSXW(v12, 0);
    v12 = VmxLoadS16(Dequant + 0);
    v12 = VmxUnpackHighSH(v12);
    v12 = VmxConvertFromSXW(v12, 0);
    v12 = VmxMulFP(v11, v12);
    v12 = VmxConvertToSXWSat(v12, 0);
    v0 = VmxAddSWS(v12, v0);
    v0 = VmxShiftRightAlgebraicW(v0, v13);
    v0 = VmxSplatW(v0, 0);
    v0 = VmxPackSWSS(v0, v0);
    VmxStoreS16(ReconData + 0, v0);
    VmxStoreS16(ReconData + 8, v0);
    VmxStoreS16(ReconData + 16, v0);
    VmxStoreS16(ReconData + 24, v0);
    VmxStoreS16(ReconData + 32, v0);
    VmxStoreS16(ReconData + 40, v0);
    VmxStoreS16(ReconData + 48, v0);
    VmxStoreS16(ReconData + 56, v0);
    Coeffs[0] = 0;
}

