// BB_runtime.Apt.cpp: the Apt runtime's bulk-build translation unit.
// Each member also compiles on its own; this file holds only their includes.
// Evidence:
// - EA's packages were built as bulk TUs named BB_<group>.<module>.cpp: the PS3 DecFIGS symbols
//   of file-local names carry BB_runtime.job_manager.cpp and BB_runtime.rwatom.cpp.
// - ARTIST holds the Apt runtime as one contiguous object, 0x82AD4898-0x82B0F14C, with the
//   members' functions interleaved across the whole range (33 of the 64 members with five or
//   more functions span more than half of it: MSVC's emission passes over one TU).
// - ARTIST's AptValue-derived constructors (AptNativeFunction 0x82AF0178, AptGlobal 0x82AF0530,
//   AptKey 0x82AF0980, AptExtern 0x82AE63D8, AptPrototype 0x82AEFEF0, ...) do not reload `this`
//   after their last call into AptValue.cpp (SetAllowDelayedDeletion/setGCRoot/setRefCount): the
//   compiler knew those callees' register use, which it does only for callees in the same TU.
// Members: the runtime sources of this tree (SDKs/EATech/Apt and SDKs/EATech/include/Apt), whose
// file split is the reconstruction's, not Apt's own. AptGlobals.cpp stays out: it is the tree's
// storage home for engine globals whose original definitions are not recovered, not an Apt
// source, and it repeats AptAnimationTarget.cpp's AptListenerEventDescriptor.
// Order: the linear order that keeps the most adjacent member transitions of ARTIST's layout
// forward (406 of 547; first member DogmaAllocator.cpp, the object's first functions at
// 0x82AD4898); members with no function ARTIST places in the range follow alphabetically.
// Several members carry per-function #pragma optimize("s", on) regions; in this TU a region a
// member leaves open also covers the members after it.

