#pragma once

#include "types.hpp"
#include <xtl.h>

namespace renderengine
{
// Xbox vertex formats are native D3D declaration words. The common names come
// from the declaration reference; ARTIST's stride table uses these SDK values.
enum VertexFormat
{
    VERTEXFORMAT_NA = -1,
    VERTEXFORMAT_UNUSED = -1,
    VERTEXFORMAT_FLOAT1 = D3DDECLTYPE_FLOAT1,
    VERTEXFORMAT_FLOAT2 = D3DDECLTYPE_FLOAT2,
    VERTEXFORMAT_FLOAT3 = D3DDECLTYPE_FLOAT3,
    VERTEXFORMAT_FLOAT4 = D3DDECLTYPE_FLOAT4,
    VERTEXFORMAT_FLOAT16_2 = D3DDECLTYPE_FLOAT16_2,
    VERTEXFORMAT_FLOAT16_4 = D3DDECLTYPE_FLOAT16_4,
    VERTEXFORMAT_SHORT2 = D3DDECLTYPE_SHORT2,
    VERTEXFORMAT_SHORT4 = D3DDECLTYPE_SHORT4,
    VERTEXFORMAT_SHORT2N = D3DDECLTYPE_SHORT2N,
    VERTEXFORMAT_SHORT4N = D3DDECLTYPE_SHORT4N,
    VERTEXFORMAT_UBYTE4 = D3DDECLTYPE_UBYTE4,
    VERTEXFORMAT_UBYTE4N = D3DDECLTYPE_UBYTE4N,
    VERTEXFORMAT_COLOR = D3DDECLTYPE_D3DCOLOR,
    VERTEXFORMAT_FORCEENUMSIZEINT = 0x7FFFFFFF
};

u32 VertexFormatGetStride(VertexFormat);
}
